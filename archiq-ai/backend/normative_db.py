# === ДАТАКЛАСС НОРМЫ ===
@dataclass
class Normative:
    code: str
    title: str
    category: str
    section: str
    content: str
    requirements: str
    min_value: Optional[float] = None
    max_value: Optional[float] = None
    unit: Optional[str] = None
    reference_type: Optional[str] = None
    year: Optional[int] = None
    tags: List[str] = None
    url: Optional[str] = None
    
    def __post_init__(self):
        if self.tags is None:
            self.tags = []


def _n(code, title, category, section, content, req, min_v=None, max_v=None, unit=None, ref_type=None, year=None, tags=None, url=None):
    """Вспомогательная функция создания Normative."""
    return Normative(
        code=code, title=title, category=category, section=section,
        content=content, requirements=req,
        min_value=min_v, max_value=max_v, unit=unit,
        reference_type=ref_type, year=year, tags=tags or [],
        url=url
    )


